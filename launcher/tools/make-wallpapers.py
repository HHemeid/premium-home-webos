#!/usr/bin/env python3
"""Generate Premium Home's bundled scenic wallpapers as original SVG artwork.

Every shape here is computed from a fixed random seed (mountain ridges by midpoint displacement,
spruce silhouettes, stars, aurora bands, mist, lake reflections), so the output is identical on
every run and contains no third-party imagery. Licence: the project owner's own artwork.

Design rules (OLED, 10-foot viewing):
  - low-to-medium luminance; the brightest areas are small (sun, moon, snow caps)
  - 1920x1080 canvas, the size webOS gives web apps; the app adds its own scrims behind text
  - gradients and plain shapes only (no filters or embedded bitmaps), so the TV decodes them cheaply

Usage: python3 -B tools/make-wallpapers.py   (writes app/assets/wallpapers/*.svg)
"""
import math
import random
from pathlib import Path

W, H = 1920, 1080
OUT = Path(__file__).resolve().parent.parent / "app" / "assets" / "wallpapers"


def f(n):
    return f"{n:.1f}".rstrip("0").rstrip(".")


def stop_tags(stops):
    """Gradient stops as (offset, colour) or (offset, colour, opacity)."""
    out = []
    for st in stops:
        o, c, a = (st + (1,))[:3]
        op = "" if a == 1 else f' stop-opacity="{a}"'
        out.append(f'<stop offset="{o}" stop-color="{c}"{op}/>')
    return "".join(out)


class Svg:
    def __init__(self, title):
        self.defs, self.body, self.n = [], [], 0
        self.title = title

    def uid(self, p):
        self.n += 1
        return f"{p}{self.n}"

    def lin(self, stops, x1=0, y1=0, x2=0, y2=1, user=None):
        gid = self.uid("g")
        units = ""
        if user:
            x1, y1, x2, y2 = user
            units = ' gradientUnits="userSpaceOnUse"'
        s = stop_tags(stops)
        self.defs.append(f'<linearGradient id="{gid}" x1="{f(x1)}" y1="{f(y1)}" x2="{f(x2)}" y2="{f(y2)}"{units}>{s}</linearGradient>')
        return f"url(#{gid})"

    def rad(self, stops, cx, cy, r, sy=1.0):
        gid = self.uid("r")
        s = stop_tags(stops)
        tr = f' gradientTransform="translate({f(cx)} {f(cy)}) scale(1 {sy}) translate({f(-cx)} {f(-cy)})"' if sy != 1 else ""
        self.defs.append(f'<radialGradient id="{gid}" cx="{f(cx)}" cy="{f(cy)}" r="{f(r)}" gradientUnits="userSpaceOnUse"{tr}>{s}</radialGradient>')
        return f"url(#{gid})"

    def add(self, el):
        self.body.append(el)

    def rect(self, fill, x=0, y=0, w=W, h=H, op=1):
        o = "" if op == 1 else f' opacity="{op}"'
        self.add(f'<rect x="{f(x)}" y="{f(y)}" width="{f(w)}" height="{f(h)}" fill="{fill}"{o}/>')

    def path(self, d, fill, op=1, extra=""):
        o = "" if op == 1 else f' opacity="{op}"'
        self.add(f'<path d="{d}" fill="{fill}"{o}{extra}/>')

    def text(self):
        return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" preserveAspectRatio="xMidYMid slice">'
                f"<title>{self.title}</title><desc>Original artwork for Premium Home, generated by tools/make-wallpapers.py.</desc>"
                f'<defs>{"".join(self.defs)}</defs>{"".join(self.body)}</svg>\n')


def displacement(rng, n, amp, rough):
    ys = [0.0] * (n + 1)
    ys[0], ys[n] = rng.uniform(-.3, .3) * amp, rng.uniform(-.3, .3) * amp
    step, scale = n, amp
    while step > 1:
        half = step // 2
        for i in range(half, n, step):
            ys[i] = (ys[i - half] + ys[i + half]) / 2 + rng.uniform(-1, 1) * scale
        step, scale = half, scale * rough
    return ys


def ridge_points(rng, base, amp, rough=0.55, levels=8, peaks=(), x0=-40, x1=W + 40, crag=.22):
    """Midpoint displacement between x0 and x1; peaks = [(x, height, width)] add summits whose
    flanks get extra crags (scaled by how high the point is), so mountains don't look like cones."""
    n = 2 ** levels
    ys = displacement(rng, n, amp, rough)
    jag = displacement(rng, n, 1.0, .62)
    pts = []
    for i, dy in enumerate(ys):
        x = x0 + (x1 - x0) * i / n
        y = base + dy
        lift = 0.0
        for px, ph, pw in peaks:
            d = abs(x - px) / pw
            if d < 1:
                lift = max(lift, ph * (1 - d) ** 1.35)
        y -= lift + jag[i] * lift * crag
        pts.append((x, y))
    return pts


def area(pts, bottom=H + 2):
    d = f"M{f(pts[0][0])} {f(bottom)} " + " ".join(f"L{f(x)} {f(y)}" for x, y in pts)
    return d + f" L{f(pts[-1][0])} {f(bottom)} Z"


def mirror(pts, axis):
    return [(x, 2 * axis - y) for x, y in pts]


def mirror_area(pts, axis, top):
    m = mirror(pts, axis)
    d = f"M{f(m[0][0])} {f(top)} " + " ".join(f"L{f(x)} {f(y)}" for x, y in m)
    return d + f" L{f(m[-1][0])} {f(top)} Z"


def spruce(x, base, h, rng, lean=0.0):
    """One spruce silhouette: a narrow spire with jagged tiers."""
    tiers = max(5, int(h / 14))
    left, right = [], []
    for i in range(tiers + 1):
        t = i / tiers
        y = base - h + h * t
        w = h * (0.035 + 0.24 * t ** 1.05) * rng.uniform(.85, 1.15)
        notch = w * 0.55
        left.append((x - w + lean * (1 - t) * h * .05, y))
        if i < tiers:
            left.append((x - notch + lean * (1 - t) * h * .05, y + h / tiers * .45))
        right.append((x + w + lean * (1 - t) * h * .05, y))
        if i < tiers:
            right.append((x + notch + lean * (1 - t) * h * .05, y + h / tiers * .45))
    trunk = [(x + h * .02, base), (x - h * .02, base)]
    pts = [(x + lean * h * .05, base - h - h * .05)] + right + trunk + list(reversed(left))
    return "M" + " L".join(f"{f(a)} {f(b)}" for a, b in pts) + " Z"


def forest(rng, pts_or_y, count, hmin, hmax, x0=-30, x1=W + 30, sink=6):
    """Trees standing on a ridge line (list of points) or a flat line (number)."""
    d = []
    for i in range(count):
        x = x0 + (x1 - x0) * (i + rng.uniform(-.4, .4)) / count
        if isinstance(pts_or_y, (int, float)):
            base = pts_or_y
        else:
            j = min(range(len(pts_or_y)), key=lambda k: abs(pts_or_y[k][0] - x))
            base = pts_or_y[j][1]
        d.append(spruce(x, base + sink, rng.uniform(hmin, hmax), rng, rng.uniform(-.3, .3)))
    return " ".join(d)


def stars(s, rng, n, ymax, color="#e8eeff", amax=.8):
    out = []
    for _ in range(n):
        r = rng.choice([.8, 1, 1, 1.2, 1.4, 1.8])
        out.append(f'<circle cx="{f(rng.uniform(0, W))}" cy="{f(rng.uniform(0, ymax) ** 1.0)}" r="{r}" fill="{color}" opacity="{rng.uniform(.15, amax):.2f}"/>')
    s.add("".join(out))


def mist(s, y, h, color, a):
    s.rect(s.lin([(0, color, 0), (.5, color, a), (1, color, 0)]), 0, y, W, h)


def shimmer(s, rng, y0, y1, n, color, amax):
    out = []
    for _ in range(n):
        y = rng.uniform(y0, y1)
        w = rng.uniform(60, 420) * (0.4 + (y - y0) / (y1 - y0))
        out.append(f'<rect x="{f(rng.uniform(-100, W))}" y="{f(y)}" width="{f(w)}" height="{f(rng.uniform(1, 2.6))}" fill="{color}" opacity="{rng.uniform(.03, amax):.3f}"/>')
    s.add("".join(out))


def vignette(s, a=.55):
    s.rect(s.rad([(0, "#000", 0), (.62, "#000", 0), (1, "#000", a)], W / 2, H * .45, W * .62, sy=.75))


