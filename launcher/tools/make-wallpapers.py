def alpine_dusk():
    rng = random.Random(11)
    s = Svg("Alpine Lake Dusk")
    hz = 690
    s.rect(s.lin([(0, "#14122b"), (.35, "#2c2347"), (.62, "#6a3d5c"), (.8, "#b8665a"), (1, "#d88a5e")], user=(0, 0, 0, hz)), 0, 0, W, hz + 2)
    s.rect(s.rad([(0, "#ffb27a", .55), (.5, "#e27a5c", .18), (1, "#e27a5c", 0)], 1180, hz - 40, 760, sy=.42))
    stars(s, rng, 40, 260, amax=.45)
    far = ridge_points(rng, 520, 70, .5, peaks=[(560, 190, 300), (900, 260, 330), (1340, 170, 260), (1640, 120, 220)])
    top = min(y for _, y in far)
    s.path(area(far), s.lin([(0, "#e9d3d6"), (.16, "#b495a8"), (.34, "#5b4566"), (1, "#3a2c4c")], user=(0, top, 0, hz)))
    mist(s, 560, 160, "#e9a07a", .16)
    mid = ridge_points(rng, 640, 40, .5, peaks=[(200, 90, 260), (1700, 110, 300)])
    s.path(area(mid), s.lin([(0, "#3a2b47"), (1, "#1d1628")], user=(0, 560, 0, hz)))
    near = ridge_points(rng, 676, 14, .45)
    s.path(forest(rng, near, 120, 26, 70, sink=10), "#120d1b")
    s.path(area(near), "#120d1b")
    # Lake with a soft mirror image of the mountains.
    s.rect(s.lin([(0, "#3a2a4a"), (.4, "#1d1527"), (1, "#07060b")], user=(0, hz, 0, H)), 0, hz, W, H - hz)
    s.path(mirror_area(far, hz, hz), s.lin([(0, "#6d5272", .55), (1, "#2a1f36", 0)], user=(0, hz, 0, hz + 260)))
    s.path(mirror_area(mid, hz, hz), s.lin([(0, "#2a1f36", .7), (1, "#120d1b", .2)], user=(0, hz, 0, hz + 120)))
    s.rect(s.rad([(0, "#ffb27a", .22), (1, "#ffb27a", 0)], 1180, hz + 30, 520, sy=.16))
    shimmer(s, rng, hz + 8, H - 40, 70, "#ffd2b0", .09)
    s.rect("#07060b", 0, hz - 1, W, 3, .6)
    vignette(s)
    return s


