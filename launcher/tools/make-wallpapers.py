def northern_lights():
    rng = random.Random(41)
    s = Svg("Northern Lights")
    hz = 760
    s.rect(s.lin([(0, "#010409"), (.5, "#04111c"), (1, "#0a2230")], user=(0, 0, 0, hz)), 0, 0, W, hz + 2)
    stars(s, rng, 160, 640, amax=.75)

    # Aurora curtains: narrow columns, each fading in from the top and out at its lower edge,
    # following a slow wave; overlapping columns read as soft, streaky light.
    def curtain(y, amp, thick, color, a, phase, freq):
        gid = s.uid("au")
        s.defs.append(f'<linearGradient id="{gid}" x1="0" y1="0" x2="0" y2="1">{stop_tags([(0, color, 0), (.6, color, a * .5), (.9, color, a), (1, color, 0)])}</linearGradient>')
        cols, out = 150, []
        for i in range(cols):
            t = i / cols
            x = -60 + (W + 120) * t
            yy = y + amp * math.sin(t * freq + phase) + amp * .35 * math.sin(t * freq * 2.7 + phase * 1.9)
            hh = thick * (0.75 + 0.5 * (0.5 + 0.5 * math.sin(t * 23 + phase * 3))) * rng.uniform(.9, 1.1)
            out.append(f'<rect x="{f(x)}" y="{f(yy - hh)}" width="{f((W + 120) / cols + 4)}" height="{f(hh)}"/>')
        return f'<g fill="url(#{gid})">' + "".join(out) + "</g>"

    aurora = "".join(curtain(*b) for b in [(420, 60, 300, "#38f2a6", .5, .3, 5.5), (360, 80, 240, "#4fd6ff", .26, 1.7, 4.2),
                                          (470, 40, 220, "#62ffc4", .36, 3.1, 7.0), (300, 55, 180, "#b48cff", .16, 4.4, 3.4)])
    s.add(aurora)
    hills = ridge_points(rng, 690, 36, .5, peaks=[(1450, 70, 380)])
    s.path(area(hills), "#061019")
    line = ridge_points(rng, 742, 12, .45)
    s.path(forest(rng, line, 130, 34, 96, sink=8), "#010306")
    s.path(area(line), "#010306")
    s.rect(s.lin([(0, "#06202a"), (1, "#010305")], user=(0, hz, 0, H)), 0, hz, W, H - hz)
    # Reflection compressed toward the shoreline, as seen at a low angle.
    s.add(f'<g transform="translate(0 {hz}) scale(1 -.42) translate(0 {-hz})" opacity=".3">{aurora}</g>')
    s.path(mirror_area(line, hz, hz), "#010306", .9)
    shimmer(s, rng, hz + 10, H - 30, 60, "#9fffe0", .07)
    vignette(s, .6)
    return s


