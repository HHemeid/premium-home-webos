def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, fn in SCENES.items():
        text = fn().text()
        (OUT / f"{name}.svg").write_text(text)
        print(f"{name}.svg  {len(text.encode()):,} bytes")


if __name__ == "__main__":
    main()
